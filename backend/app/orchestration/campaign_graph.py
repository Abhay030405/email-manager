def _now_iso() -> str:
	return datetime.now(tz=timezone.utc).isoformat()


async def call_mock_api_with_retry(func: Callable, *args: Any, max_retries: int = MAX_RETRIES, **kwargs: Any) -> Any:
	"""Wrapper for Mock API calls with exponential backoff (5s → 10s → 20s).

	Non-retriable errors (400, 404) are re-raised immediately.
	"""
	import requests

	last_exc: Exception | None = None
	for attempt in range(1, max_retries + 1):
		try:
			return func(*args, **kwargs)
		except MockCampaignAPIError as exc:
			if exc.status_code in (400, 404):
				raise  # validation/not-found errors — don't retry
			last_exc = exc
		except requests.exceptions.Timeout as exc:
			last_exc = exc
			logger.warning("Mock API timeout (attempt %d/%d)", attempt, max_retries)
		except requests.exceptions.HTTPError as exc:
			if exc.response is not None and exc.response.status_code in (502, 503):
				last_exc = exc
				logger.warning("Mock API service unavailable (attempt %d/%d)", attempt, max_retries)
			else:
				raise
		except Exception as exc:
			last_exc = exc
			logger.warning("Mock API error (attempt %d/%d): %s", attempt, max_retries, exc)

		if attempt < max_retries:
			wait = 5 * (2 ** (attempt - 1))  # 5s, 10s, 20s
			await asyncio.sleep(wait)

	raise last_exc  # type: ignore[misc]


